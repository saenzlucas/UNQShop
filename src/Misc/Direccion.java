package Misc;

public class Direccion {
	
	private int zip;
	private int number;
	private String street;
	private String locality;
	
	public Direccion(int zip, int number, String street, String locality) {
		this.zip = zip;
		this.number = number;
		this.street = street;
		this.locality = locality;
	}
	
}
